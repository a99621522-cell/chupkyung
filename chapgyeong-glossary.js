const ORDER = Object.keys(G).sort((a,b)=>b.length-a.length); // 긴 용어 먼저(살인상생 > 살)
function gloss(text, opt = {}) {
  let out = String(text); const done = new Set(opt.already || []);
  // 1) 이미 「용어(漢字)」로만 붙은 곳은 풀이를 채움
  for (const term of ORDER) { const [hanja, mean] = G[term]; if (!hanja) continue; out = out.replace(new RegExp(term + '\\(' + hanja + '\\)(?!,)', 'g'), () => { done.add(term); return `${term}(${hanja}, ${mean})`; }); }
  for (const term of ORDER) {
    if (done.has(term)) continue;
    const re = new RegExp(term + '(?![가-힣]*\\()'); // 뒤에 곧바로 괄호 풀이가 붙어 있으면 건너뜀
    const m = re.exec(out); if (!m) continue;
    const [hanja, mean] = G[term]; const rep = hanja ? `${term}(${hanja}, ${mean})` : `${term}(${mean})`;
    // 이미 다른 용어의 풀이 괄호 안이면 건너뜀
    const before = out.slice(0, m.index); const open = (before.match(/\(/g)||[]).length, close = (before.match(/\)/g)||[]).length; if (open > close) continue;
    out = before + rep + out.slice(m.index + term.length); done.add(term);
  }
  return out;
}
